#!/usr/bin/env node
// Builds the self-hosted icon font (docs/DESIGN_SYSTEM.md → Icons).
//
//   npm run icons          needs python3 with fonttools and brotli
//                          (pip install fonttools brotli; PYTHON=… to pick one)
//
// The full Tabler webfont is 447 KB of WOFF2 for ~5,000 icons behind a
// render-blocking third-party stylesheet; the app uses about a hundred. This
// downloads Tabler Icons TABLER_VERSION from npm, keeps only the glyphs the
// app uses (scripts/lib/icons.mjs) and writes the font and its stylesheet.
// Both are committed, so building the app needs no Python;
// src/styles/__tests__/icons.test.js fails when a used icon is missing, which
// is the cue to run this again.
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { ICON_CSS, ICON_FONT, TABLER_VERSION, usedIconClasses } from './lib/icons.mjs';

const tmp = mkdtempSync(join(tmpdir(), 'tabler-'));
try {
  execFileSync('npm', ['pack', `@tabler/icons-webfont@${TABLER_VERSION}`, '--pack-destination', tmp, '--silent'], { stdio: ['ignore', 'ignore', 'inherit'] });
  execFileSync('tar', ['xzf', join(tmp, `tabler-icons-webfont-${TABLER_VERSION}.tgz`), '-C', tmp, 'package/dist/tabler-icons.min.css', 'package/dist/fonts/tabler-icons.woff2']);
  const css = readFileSync(join(tmp, 'package/dist/tabler-icons.min.css'), 'utf8');
  const codepoint = new Map([...css.matchAll(/\.(ti-[a-z0-9-]+):before\{content:"\\([0-9a-f]+)"\}/g)].map((m) => [m[1], m[2]]));
  const base = css.match(/\.ti\{[^}]+\}/)?.[0];
  if (!base || codepoint.size < 1000) throw new Error(`Unexpected stylesheet layout in Tabler Icons ${TABLER_VERSION}`);

  const used = usedIconClasses();
  const unknown = used.filter((name) => !codepoint.has(name));
  if (unknown.length) throw new Error(`Not in Tabler Icons ${TABLER_VERSION} (typo, or a newer icon): ${unknown.join(', ')}`);

  mkdirSync(dirname(ICON_FONT), { recursive: true });
  execFileSync(process.env.PYTHON || 'python3', [
    '-m', 'fontTools.subset', join(tmp, 'package/dist/fonts/tabler-icons.woff2'),
    `--unicodes=${used.map((name) => `U+${codepoint.get(name)}`).join(',')}`,
    '--flavor=woff2',
    '--layout-features=', // icons are addressed by code point; no ligatures needed
    '--name-IDs=*', // keep the copyright and licence records
    `--output-file=${ICON_FONT}`,
  ], { stdio: 'inherit' });

  writeFileSync(ICON_CSS, [
    '/*!',
    ` * Tabler Icons ${TABLER_VERSION} by tabler - https://tabler.io`,
    ' * License (MIT) - https://github.com/tabler/tabler-icons/blob/master/LICENSE',
    ` * Subset to the ${used.length} icons this app uses. Generated by scripts/build-icon-subset.mjs: do not edit.`,
    ' */',
    // block, as the CDN stylesheet behaved: icons are private-use code points,
    // so a fallback font would paint empty boxes while the font loads.
    '@font-face{font-family:"tabler-icons";font-style:normal;font-weight:400;font-display:block;src:url("./fonts/tabler-icons-subset.woff2") format("woff2")}',
    base,
    ...used.map((name) => `.${name}:before{content:"\\${codepoint.get(name)}"}`),
    '',
  ].join('\n'));
  console.log(`${used.length} icons → ${ICON_FONT} (${(statSync(ICON_FONT).size / 1024).toFixed(1)} KB), ${ICON_CSS}`);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
