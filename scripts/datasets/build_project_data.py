"""Build the data modules for the V4 applied projects (docs/v4/APPLIED_PROJECTS.md).

Real datasets are read from files downloaded from their publishers; synthetic
ones are generated here with fixed seeds, so every number in the app can be
reproduced. Writes src/data/projects/data/*.js and prints a provenance summary
(row counts and SHA-256 of each source file).

    python3 -I scripts/datasets/build_project_data.py PENGUINS_CSV CET_TXT WDBC_DATA

Sources (checked 2026-10-24):
  penguins.csv  https://raw.githubusercontent.com/allisonhorst/palmerpenguins/main/inst/extdata/penguins.csv  (CC0)
  CET           https://www.metoffice.gov.uk/hadobs/hadcet/data/meantemp_monthly_totals.txt  (Open Government Licence)
  wdbc.data     https://archive.ics.uci.edu/static/public/17/breast+cancer+wisconsin+diagnostic.zip  (CC BY 4.0)
"""

import csv
import hashlib
import json
import pathlib
import sys

import numpy as np

OUT = pathlib.Path(__file__).resolve().parents[2] / "src" / "data" / "projects" / "data"


def sha256(path):
    return hashlib.sha256(pathlib.Path(path).read_bytes()).hexdigest()


def write_module(name, header, exports):
    lines = [f"// {line}" if line else "//" for line in header] + ["// Generated by scripts/datasets/build_project_data.py — do not edit by hand.", ""]
    for key, value in exports.items():
        if isinstance(value, str):
            lines.append(f"export const {key} = {json.dumps(value)};")
        else:
            lines.append(f"export const {key} = {json.dumps(value, separators=(',', ':'))};")
    (OUT / f"{name}.js").write_text("\n".join(lines) + "\n")


def penguins(path):
    text = pathlib.Path(path).read_text().replace("\r\n", "\n").strip() + "\n"
    rows = list(csv.DictReader(text.splitlines()))
    write_module("penguins", [
        "Palmer Penguins: Gorman, Williams & Fraser (2014), PLoS ONE 9(3): e90081; Palmer Station LTER.",
        "Licence: CC0 (github.com/allisonhorst/palmerpenguins). Missing values are the literal NA, as published.",
    ], {"PENGUINS_CSV": text})
    return f"penguins: {len(rows)} rows, sha256 {sha256(path)}"


def cet(path):
    lines = pathlib.Path(path).read_text().splitlines()
    table = {}
    for line in lines:
        parts = line.split()
        if len(parts) == 14 and parts[0].isdigit() and len(parts[0]) == 4:
            table[int(parts[0])] = [float(v) for v in parts[1:13]]
    years = list(range(1991, max(table) + 1))
    write_module("cet", [
        "Met Office Hadley Centre Central England Temperature (HadCET), monthly mean °C, 1991 onwards.",
        "Contains public sector information licensed under the Open Government Licence v3.0.",
        "-99.9 marks a month not yet recorded, exactly as in the source file.",
    ], {"CET_YEARS": years, "CET_MONTHLY": [table[y] for y in years]})
    return f"cet: {years[0]}–{years[-1]}, sha256 {sha256(path)}"


def wdbc(path):
    rows = [line.strip().split(",") for line in pathlib.Path(path).read_text().splitlines() if line.strip()]
    radius = [float(r[2]) for r in rows]          # column 3: radius (mean)
    malignant = [1 if r[1] == "M" else 0 for r in rows]
    write_module("wdbc", [
        "Breast Cancer Wisconsin (Diagnostic): Wolberg, Mangasarian, Street & Street (1993), UCI ML Repository,",
        "doi:10.24432/C5DW2B. Licence: CC BY 4.0. Only two columns are kept: mean radius of the cell nuclei",
        "in the image (column 3) and the diagnosis (1 = malignant, 0 = benign).",
    ], {"WDBC_RADIUS": radius, "WDBC_MALIGNANT": malignant})
    return f"wdbc: {len(rows)} rows ({sum(malignant)} malignant), sha256 {sha256(path)}"


def synthetic():
    # Restaurant soup demand: 8 weeks × 7 days. Weekday base + normal noise (sd 6), seed 7.
    rng = np.random.default_rng(7)
    base = np.array([42, 45, 48, 55, 78, 92, 60])
    demand = np.clip(np.round(base + rng.normal(0, 6, size=(8, 7))), 0, None).astype(int)
    write_module("restaurant", [
        "SYNTHETIC: soup portions demanded per day over 8 weeks (Mon–Sun), invented for this course.",
        "Generated as round(base[weekday] + Normal(0, 6)) with base = [42, 45, 48, 55, 78, 92, 60], seed 7.",
    ], {"SOUP_DEMAND": demand.tolist()})

    # Price and weekly units: prices set at random (like an experiment), seed 11.
    rng = np.random.default_rng(11)
    price = np.round(rng.uniform(4.0, 8.0, size=40), 1)
    units = np.round(520 - 45 * price + rng.normal(0, 18, size=40)).astype(int)
    write_module("price_demand", [
        "SYNTHETIC: 40 weeks of price and units sold, invented for this course.",
        "Prices drawn uniformly from $4.00–$8.00 (as in a randomized pricing test); units = round(520 − 45·price + Normal(0, 18)), seed 11.",
    ], {"WEEK_PRICE": price.tolist(), "WEEK_UNITS": units.tolist()})
    return "synthetic: restaurant 8×7, price_demand 40 weeks"


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    OUT.mkdir(parents=True, exist_ok=True)
    for line in (penguins(sys.argv[1]), cet(sys.argv[2]), wdbc(sys.argv[3]), synthetic()):
        print(line)
