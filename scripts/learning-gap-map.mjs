// Generates docs/learning-8020/COURSE_GAP_MAP.md from the catalog, the
// learning path and the next-action engine: for every course on the default
// route, what is written and what is only planned, what it builds on, what
// a learner is offered once its written lessons are done, and the bridge
// each written lesson offers after wrong answers.
//
//   npm run docs:gaps

import { writeFileSync } from 'node:fs';
import { CURRICULUM as cur } from '../src/data/curriculum/path.js';
import { problemsForLesson } from '../src/data/curriculum/problems.js';
import { PRIORITY_LESSONS } from '../src/data/curriculum/priority.js';
import { getNextLearningAction, bridgeFor, firstGap, courseCompletion } from '../src/lib/nextAction.js';

const OUT = 'docs/learning-8020/COURSE_GAP_MAP.md';
const route = cur.pathById[cur.defaultPath];
const priority = new Set(PRIORITY_LESSONS.map((p) => p.id));
const title = (id) => cur.courseById[id]?.title ?? id;
const esc = (s) => String(s).replace(/\|/g, '\\|');

const lines = [
  '# Course gap map',
  '',
  '_Generated by `npm run docs:gaps` (scripts/learning-gap-map.mjs) from the catalog, the learning path and the next-action engine. Do not edit by hand._',
  '',
  `Route: **${route.title}** (${route.courses.length} courses). “Written” lessons are real lessons with questions and a checkpoint; “planned” are titles in the catalog only. Self-study preparation: nothing here is college credit or an official course equivalence.`,
  '',
  '## Courses',
  '',
  '| # | Course | Builds on | Written | Planned | Units with no lesson | When the written lessons are done |',
  '|---|---|---|---|---|---|---|',
];

let totalWritten = 0;
let totalPlanned = 0;
for (const [i, id] of route.courses.entries()) {
  const course = cur.courseById[id];
  const written = cur.courseLessons[id];
  const c = courseCompletion(cur, { lessons: {}, status: {} }, id);
  totalWritten += c.written;
  totalPlanned += c.planned;
  const lessons = Object.fromEntries(written.map((l, k) => [l, { completed: k + 1 }]));
  const a = written.length ? getNextLearningAction(cur, { state: { lessons, status: {} }, from: { courseId: id } }) : null;
  const after = !a ? 'No written lesson yet'
    : a.evidence.ruleId === 'content-gap' ? `Moves on: “${a.label}”; gap named: “${firstGap(course)?.title}”${a.alternatives.some((x) => x.kind === 'practice') ? '; practice offered' : ''}`
      : a.kind === 'path-finished' ? 'End of the written path (named as such)'
        : `${a.kind}: ${a.label}`;
  const empty = course.units.filter((u) => !u.lessons.length).length;
  lines.push(`| ${i + 1} | ${esc(course.title)} | ${course.prerequisites.map(title).map(esc).join(', ') || '—'} | ${c.written} | ${c.planned} | ${empty} of ${course.units.length} | ${esc(after)} |`);
}
lines.push('', `**Totals:** ${totalWritten} written lessons, ${totalPlanned} planned. Every course on the route has at least one written lesson; none has every planned lesson written.`, '');

lines.push('## Written lessons: applied problems and bridges', '', 'A bridge is offered after two misses that outnumber the hits in a lesson, or a checkpoint under half right (src/lib/nextAction.js). ★ marks the five priority lessons (docs/learning-8020/PRIORITY_SCORECARD.md).', '');
lines.push('| Course | Lesson | Applied problems | Faded example | Bridge after wrong answers |', '|---|---|---|---|---|');
for (const id of route.courses) {
  for (const l of cur.courseLessons[id]) {
    const b = bridgeFor(cur, l);
    const n = problemsForLesson(l).length;
    lines.push(`| ${esc(title(id))} | ${priority.has(l) ? '★ ' : ''}${esc(cur.lessonById[l].title)} | ${n} | ${priority.has(l) ? 'yes' : '—'} | ${b ? `${esc(cur.lessonById[b.lessonId].title)} (${b.minutes} min)` : 'none: nothing written teaches what it builds on'} |`);
  }
}
lines.push('');

writeFileSync(OUT, `${lines.join('\n')}\n`);
console.log(`wrote ${OUT}`);
