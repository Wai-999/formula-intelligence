/** 'authored' when every unit is fully written, 'partial' when some lessons are, 'outline' when none are. */
export function courseStatus(course) {
  const authored = course.units.reduce((n, u) => n + u.lessons.length, 0);
  const planned = course.units.reduce((n, u) => n + u.planned.length, 0);
  if (authored === 0) return 'outline';
  return planned === 0 ? 'authored' : 'partial';
}

export function unitStatus(unit) {
  if (unit.lessons.length === 0) return 'outline';
  return unit.planned.length === 0 ? 'authored' : 'partial';
}
