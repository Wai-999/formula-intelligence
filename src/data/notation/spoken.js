/**
 * True for a symbol that is just English words (“Range”, “margin of error”,
 * “max_depth”), which reads as itself and needs no entry. A single letter,
 * a digit, an abbreviation (“IQR”) or any mathematical sign is notation.
 */
export const isPlainWords = (symbol) => symbol.split(/[\s_/,&-]+/).filter(Boolean).every((w) => /^[A-Za-z][a-z]+$/.test(w));

/** How to say a Formula map symbol, or null when it is plain words. */
export const spokenFor = (symbol) => SPOKEN[symbol] ?? null;
